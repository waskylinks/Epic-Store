// ─── VALIDATION ───────────────────────────────────────────────────────────────

/**
 * validateAnalyticsEvent
 *
 * Validates that a built event has all required fields before it is
 * enqueued. Returns { valid: boolean, errors: string[] }.
 *
 * Call this in development to catch schema issues early.
 * In production the queue will still process events with minor issues
 * but log them to the observability layer.
 *
 * @param {Object} event - Output of buildAnalyticsEvent()
 * @returns {{ valid: boolean, errors: string[] }}
 */
export const validateAnalyticsEvent = (event) => {
  const errors = [];

  if (!event.event_id)   errors.push('event_id is required');
  if (!event.event_type) errors.push('event_type is required');
  if (!event.event_source || !['client', 'server'].includes(event.event_source)) {
    errors.push('event_source must be "client" or "server"');
  }
  if (!event.event_time_server) errors.push('event_time_server is required');
  if (!event.schema_version)    errors.push('schema_version is required');

  // Warn (not error) if both user_id and anonymous_id are null
  // This is valid for some public page_view events but unusual for purchase events
  if (!event.user_id && !event.anonymous_id) {
    errors.push('WARNING: both user_id and anonymous_id are null — event cannot be attributed to any identity');
  }

  return {
    valid:  errors.filter(e => !e.startsWith('WARNING')).length === 0,
    errors,
  };
};

